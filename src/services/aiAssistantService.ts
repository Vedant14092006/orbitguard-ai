// Check for secure backend endpoint or LLM proxy
const BACKEND_LLM_ENDPOINT = typeof import.meta !== 'undefined' && import.meta.env
  ? (import.meta.env.VITE_AI_BACKEND_URL || import.meta.env.VITE_LLM_ENDPOINT || '')
  : '';

/**
 * Main function to generate ASTRA AI response.
 * Uses a secure backend LLM if configured; otherwise seamlessly uses
 * the high-accuracy local aerospace knowledge & telemetry engine.
 */
export async function queryAstraAssistant(userPrompt: string): Promise<ChatMessage> {
  // If a secure backend proxy endpoint is configured, attempt remote LLM call
  if (BACKEND_LLM_ENDPOINT) {
    try {
      const response = await fetch(BACKEND_LLM_ENDPOINT, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          prompt: userPrompt,
          context: {
            catalogSatellitesCount: MOCK_SATELLITES.length,
            catalogDebrisCount: MOCK_DEBRIS.length,
            activeConjunctionsCount: MOCK_CONJUNCTIONS.length,
            spaceWeather: CURRENT_SPACE_WEATHER
          }
        })
      });

      if (response.ok) {
        const data = await response.json();
        return {
          id: 'msg-' + Date.now(),
          sender: 'astra',
          timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' }),
          text: data.text || data.message || 'Telemetry acknowledged.',
          dataCard: data.dataCard
        };
      }
    } catch {
      // Backend request failed or timed out — fall back cleanly to local knowledge engine
    }
  }

  // Built-in intelligent aerospace knowledge engine (Functional Fallback)
  return generateAstraResponse(userPrompt);
}

